import assert from 'node:assert/strict';
import { readFileSync, existsSync } from 'node:fs';
const root = new URL('../', import.meta.url);
const pkg = JSON.parse(readFileSync(new URL('package.json', root), 'utf8'));
const editions = JSON.parse(readFileSync(new URL('build/editions.json', root), 'utf8'));
assert.equal(pkg.name, 'pi-furry-partner');
assert.ok(pkg.pi.extensions.includes('./index.ts'));
assert.ok(!pkg.dsh && !pkg.main && !pkg.exports);
assert.deepEqual(Object.keys(editions.platforms), ['pi']);
for (const name of ['lib/index.js','lib/client.js','lib/dsh-bridge.mjs','cordis.patch.yml','tests/run-dsh.mjs']) assert.ok(!existsSync(new URL(name, root)), name);
assert.ok(!Object.keys(pkg.scripts).some(name => name.includes('dsh')));
console.log('Pi product isolation: Pi entry/package only; no DSH Host, Client, bundle or test entry.');
