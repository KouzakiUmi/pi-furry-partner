#!/usr/bin/env node
// Build self-contained DSH Web Client bundle (lib/client.js) without external bundlers.
import assert from "node:assert/strict";
import { readFile, writeFile } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");

function stripEsmModuleSyntax(source) {
  return source
    .replace(/^\s*import\s+[^;]+;\s*$/gm, "")
    .replace(/^\s*export\s+(const|let|var|function|async\s+function)\s+/gm, "$1 ")
    .replace(/^\s*export\s*\{[^}]*\};?\s*$/gm, "");
}

const moduleOrder = [
  "build-profile.mjs",
  "styles.mjs",
  "expressions.mjs",
  "gestures.mjs",
  "gesture-video.mjs",
  "approved-motion-codec.mjs",
  "approved-motion.mjs",
  "poke.mjs",
  "listen.mjs",
  "watch.mjs",
  "search.mjs",
  "language.mjs",
  "activity.mjs",
  "motion.mjs",
  "response-latency.mjs",
  "dsh-bridge.mjs",
  "dsh-companion.mjs",
  "dsh-presentation.mjs",
  "dsh-scene-title.mjs",
];

const chunks = [];
for (const filename of moduleOrder) {
  let raw = await readFile(join(root, "lib", filename), "utf8");
  if (filename === "language.mjs") {
    raw = raw
      .replace(/import\s+\{\s*spawnSync\s*\}\s+from\s+"node:child_process";/, "const spawnSync = () => ({ status: 1, stdout: '' });")
      .replace(/import\s+\{\s*join\s*\}\s+from\s+"node:path";/, "const join = (...parts) => parts.join('/');")
      .replace(
        "env = process.env, platform = process.platform,",
        "env = (typeof process !== 'undefined' && process?.env) || {}, platform = (typeof process !== 'undefined' && process?.platform) || 'browser',"
      )
      .replace(
        "readIntlLocale = () => Intl.DateTimeFormat().resolvedOptions().locale",
        "readIntlLocale = () => (typeof navigator !== 'undefined' && navigator.language) || Intl.DateTimeFormat().resolvedOptions().locale"
      );
  }
  chunks.push(`// ── ${filename} ──\n${stripEsmModuleSyntax(raw).trim()}`);
}

const voices = {
  "zh-CN": {
    copy: JSON.parse(await readFile(join(root, "assets/status-copy.json"), "utf8")),
    phrases: JSON.parse(await readFile(join(root, "assets/status-phrases.json"), "utf8")),
  },
  en: {
    copy: JSON.parse(await readFile(join(root, "assets/status-copy.en.json"), "utf8")),
    phrases: JSON.parse(await readFile(join(root, "assets/status-phrases.en.json"), "utf8")),
  },
};

// Keep each startup seed in its selected artwork style; no pixel/illustration flash.
const seedSheets = {};
for (const [style, directory] of [['umi', 'umi'], ['umi-pixel', 'pixel']]) {
  const raw = JSON.parse(await readFile(join(root, 'assets/reactions', directory, 'reaction-sheet.json'), 'utf8'));
  const frames = [], ids = {};
  for (const id of ['idle-open', 'idle-blink', 'think']) {
    const frame = raw.frames[raw.ids[id]];
    if (!frame) continue;
    ids[id] = frames.length;
    frames.push({ id, pixels: Buffer.from(frame.pixels).toString('base64') });
  }
  seedSheets[style] = { schemaVersion: 1, style, approvedStaticRevision: raw.approvedStaticRevision,
    width: raw.width, height: raw.height, transparentIndex: raw.transparentIndex ?? 0,
    palette: raw.palette, ids, frames,
    motion: { ears: raw.motion?.ears, paws: raw.motion?.paws, approvedWholeFrames: raw.motion?.approvedWholeFrames } };
}

const clientSourceRaw = await readFile(join(root, "lib/dsh-client-source.js"), "utf8");
const clientSource = stripEsmModuleSyntax(clientSourceRaw).trim();

const output = `// DeepSeek Harness (DSH) Client bundle for pi-furry-partner (Umi / 呜咪).
// Generated by scripts/build-dsh-client.mjs — do not edit by hand.
window.__ModuleLoader__.load({
  id: "pi-furry-partner",
  factory: (require) => {
    var module = { exports: {} };
    var exports = module.exports;
    Object.defineProperty(exports, Symbol.toStringTag, { value: "Module" });
    Object.defineProperty(exports, "__esModule", { value: true });

    const React = require("react");

${chunks.join("\n\n")}

// ── Embedded Localized Copy & Seed Sprite Sheet ──
const EMBEDDED_VOICES = ${JSON.stringify(voices)};
const SEED_SHEETS = ${JSON.stringify(seedSheets)};

// ── DSH Client Source ──
${clientSource}

    const name = "pi-furry-partner/client";
    const inject = ["slots"];

    function apply(ctx) {
      const controller = createMascotController();
      const components = createMascotComponents(React, controller);
      bindDshRuntime(ctx, React, controller, components);
      return controller;
    }

    exports.name = name;
    exports.inject = inject;
    exports.apply = apply;
    exports.createMascotController = createMascotController;
    exports.createMascotComponents = createMascotComponents;
    exports.createDshBridge = createDshBridge;
    exports.bindDshRuntime = bindDshRuntime;
    exports.resolveMascotPixels = resolveMascotPixels;
    return module.exports;
  },
});
`;

const targetPath = join(root, "lib/client.js");
await writeFile(targetPath, output, "utf8");
assert.ok(output.includes('id: "pi-furry-partner"'));
console.log(`Built ${targetPath} (${Math.round(Buffer.byteLength(output, "utf8") / 1024)} KB).`);
